export function getDefaultRegistry(): { config: ModelRegistryConfig; models: ModelInfo[] } {
  return { config: DEFAULT_CONFIG, models: [...DEFAULT_MODELS] };
}

export function getModelById(models: ModelInfo[], id: string): ModelInfo | null {
  return models.find((m) => m.id === id) ?? null;
}

export function getModelsByProvider(models: ModelInfo[], provider: ModelProvider): ModelInfo[] {
  return models.filter((m) => m.provider === provider);
}

export function getConfiguredModels(models: ModelInfo[]): ModelInfo[] {
  return models.filter((m) => m.isConfigured);
}

export function isCapabilitySupported(model: ModelInfo, capability: ModelCapability): boolean {
  return model.capabilities.includes(capability);
}

export const modelRegistry = {
  getDefaultRegistry,
  getModelById,
  getModelsByProvider,
  getConfiguredModels,
  isCapabilitySupported,
  PROVIDER_ENDPOINTS,
  DEFAULT_CONFIG,
  DEFAULT_MODELS,
};
